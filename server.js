app.post("/api/admin/products", adminOnly, async (req, res) => {
  try {
    const {
      name,
      category,
      description = "",
      price = 0,
      image = "",
      active = 1,
      featured = 0
    } = req.body;

    if (!name || !category) {
      return res.status(400).json({
        error: "Nombre y categoría son obligatorios"
      });
    }

    const maxResult = usePostgres
      ? await db.query(
          `SELECT COALESCE(MAX(sort_order),0) AS max
           FROM products
           WHERE category=$1`,
          [category]
        )
      : await db.query(
          `SELECT COALESCE(MAX(sort_order),0) AS max
           FROM products
           WHERE category=?`,
          [category]
        );

    const maxOrder = Number(
      maxResult.rows[0]?.max || 0
    );

    if (usePostgres) {
      const result = await db.query(
        `INSERT INTO products
         (name,category,description,price,image,active,featured,sort_order)
         VALUES($1,$2,$3,$4,$5,$6,$7,$8)
         RETURNING id`,
        [
          name,
          category,
          description,
          Number(price) || 0,
          image,
          active ? 1 : 0,
          featured ? 1 : 0,
          maxOrder + 1
        ]
      );

      return res.json({
        ok: true,
        id: result.rows[0].id
      });
    }

    const result = await db.query(
      `INSERT INTO products
       (name,category,description,price,image,active,featured,sort_order)
       VALUES(?,?,?,?,?,?,?,?)`,
      [
        name,
        category,
        description,
        Number(price) || 0,
        image,
        active ? 1 : 0,
        featured ? 1 : 0,
        maxOrder + 1
      ]
    );

    res.json({
      ok: true,
      id: null
    });
  } catch (error) {
    console.error("Error creando producto:", error);

    res.status(500).json({
      error: "No se pudo crear el producto"
    });
  }
});

