const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    cb(null, UPLOAD_DIR);
  },

  filename: (req, file, cb) => {
    const ext = path
      .extname(file.originalname)
      .toLowerCase();

    const safe =
      Date.now() +
      "-" +
      Math.random()
        .toString(36)
        .slice(2, 8) +
      ext;

    cb(null, safe);
  }
});

const upload = multer({
  storage,

  limits: {
    fileSize: 4 * 1024 * 1024
  },

  fileFilter: (req, file, cb) => {
    const ok = [
      "image/jpeg",
      "image/png",
      "image/webp",
      "image/jpg"
    ].includes(file.mimetype);

    cb(
      ok
        ? null
        : new Error("Solo JPG, PNG o WEBP"),
      ok
    );
  }
});

app.post(
  "/api/admin/upload",
  adminOnly,
  upload.single("image"),
  (req, res) => {
    if (!req.file) {
      return res.status(400).json({
        error: "No se recibió imagen"
      });
    }

    res.json({
      ok: true,
      url: "/uploads/" + req.file.filename
    });
  }
);

