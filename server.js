async function initDatabase() {
  if (usePostgres) {
    const { Pool } = require("pg");

    pgPool = new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.NODE_ENV === "production"
        ? { rejectUnauthorized: false }
        : false
    });

    db = {
      query: async (text, params = []) => {
        return pgPool.query(text, params);
      }
    };

    await db.query(`
      CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      );

      CREATE TABLE IF NOT EXISTS products (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        category TEXT NOT NULL,
        description TEXT DEFAULT '',
        price INTEGER NOT NULL DEFAULT 0,
        image TEXT DEFAULT '',
        active INTEGER NOT NULL DEFAULT 1,
        featured INTEGER NOT NULL DEFAULT 0,
        sort_order INTEGER NOT NULL DEFAULT 0
      );
    `);

    console.log("Base de datos PostgreSQL conectada.");
  } else {
    const sqliteSync = require("sqlite-sync");

    const dbPath = path.join(ROOT, "nonna.db");
    sqliteSync.connect(dbPath);
    sqlite = sqliteSync;

    sqlite.run(`
      CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      );

      CREATE TABLE IF NOT EXISTS products (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        category TEXT NOT NULL,
        description TEXT DEFAULT '',
        price INTEGER NOT NULL DEFAULT 0,
        image TEXT DEFAULT '',
        active INTEGER NOT NULL DEFAULT 1,
        featured INTEGER NOT NULL DEFAULT 0,
        sort_order INTEGER NOT NULL DEFAULT 0
      );
    `);

  db = {
  query: async (sql, params = []) => {
    const result = sqlite.run(sql, params);

    /*
      sqlite-sync puede devolver una consulta SELECT
      con esta estructura:

      [
        {
          columns: ["id", "name", ...],
          values: [
            [1, "Muzzarella", ...],
            [2, "Jamón y Morrón", ...]
          ]
        }
      ]

      Convertimos esa estructura a:

      [
        {
          id: 1,
          name: "Muzzarella",
          ...
        }
      ]
    */

    let data = result;

    // sqlite-sync puede envolver el resultado en un array
    if (
      Array.isArray(data) &&
      data.length === 1 &&
      data[0] &&
      Array.isArray(data[0].columns) &&
      Array.isArray(data[0].values)
    ) {
      data = data[0];
    }

    // Resultado SELECT con columns + values
    if (
      data &&
      Array.isArray(data.columns) &&
      Array.isArray(data.values)
    ) {
      const rows = data.values.map(values => {
        const row = {};

        data.columns.forEach((column, index) => {
          row[column] = values[index];
        });

        return row;
      });

      return {
        rows,
        rowCount: rows.length
      };
    }

    // Resultado que ya viene como array de objetos
    if (Array.isArray(data)) {
      return {
        rows: data,
        rowCount: data.length
      };
    }

    // Consultas que no devuelven filas
    return {
      rows: [],
      rowCount: 0
    };
  }
};

    console.log("Base de datos SQLite local conectada.");
  }

  await seedDatabase();
}

